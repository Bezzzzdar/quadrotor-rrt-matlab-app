function [summary, statistics] = summarizeComparison(samples, configurations)
%SUMMARIZECOMPARISON Считает статистику с явным числом пропусков и бесконечностей.
% Условные метрики и неудачи: https://www.kavrakilab.org/publications/moll-sucan2015benchmarking-motion-planning.pdf
    summaryRows = cell(numel(configurations), 1);
    metricNames = {'CalculationTime_s', 'PathLength_m', 'MaxCurvature_1_m', 'MeanCurvature_1_m'};
    statisticRows = cell(4*numel(configurations), 1);
    for index = 1:numel(configurations)
        selected = samples(samples.Configuration == string(configurations(index).Name), :);
        count = height(selected);
        summaryRows{index} = table(string(configurations(index).Name), string(configurations(index).Planner), ...
            count, sum(selected.PlanningSolved), sum(selected.Solved), ...
            sum(selected.PlanningSolved)/count, sum(selected.Solved)/count, ...
            sum(selected.Status == "no_path"), sum(selected.Status == "timeout"), ...
            sum(selected.Status == "error"), sum(selected.Status == "invalid_path"), ...
            sum(selected.Status == "invalid_trajectory"), ...
            'VariableNames', {'Configuration', 'Planner', 'RunCount', 'PlanningSolvedRuns', ...
            'SolvedRuns', 'PlanningSuccessRate', 'TrajectorySuccessRate', 'NoPathRuns', ...
            'TimeoutRuns', 'ErrorRuns', 'InvalidPathRuns', 'InvalidTrajectoryRuns'});
        for metric = 1:4
            eligible = selected.Solved;
            if metric == 1, eligible = selected.PlanningSolved; end
            values = selected.(metricNames{metric});
            values = values(eligible & ~isnan(values));
            stats = nan(1, 7);
            if ~isempty(values)
                stats = [mean(values), std(values), median(values), ...
                    quantile(values, [0.25, 0.75]), min(values), max(values)];
            end
            statisticRows{4*(index-1)+metric} = table(string(configurations(index).Name), ...
                string(metricNames{metric}), numel(values), count-numel(values), sum(isinf(values)), ...
                stats(1), stats(2), stats(3), stats(4), stats(5), stats(6), stats(7), ...
                'VariableNames', {'Configuration', 'Metric', 'AvailableRuns', 'MissingRuns', ...
                'UnboundedRuns', 'Mean', 'Std', 'Median', 'Q1', 'Q3', 'Min', 'Max'});
        end
    end
    summary = vertcat(summaryRows{:});
    statistics = vertcat(statisticRows{:});
end
